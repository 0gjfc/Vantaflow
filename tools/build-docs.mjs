// Regenerates docs/compatibility.md and docs/customization.md from the shared JSON, so the
// documentation always matches what the app uses. Run: node tools/build-docs.mjs
import fs from 'node:fs';

const read = (p) => JSON.parse(fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8'));
const write = (p, text) => fs.writeFileSync(new URL(`../${p}`, import.meta.url), `${text.trim()}\n`);
const fwText = (s) => (s.versions ? s.versions.join(', ') : `${s.range[0]}–${s.range[1]}`);
const cell = (t) => String(t).replace(/\|/g, '\\|');

function environmentDoc(d, platform) {
  const rows = d.releases.map((r) => {
    const fw = r.firmware.length ? r.firmware.map((s) => `${fwText(s)}${s.level === 'limited' ? ' *(limited)*' : ''}`).join('<br>') : '— *(no firmware statement)*';
    const ev = r.firmware.map((s) => s.evidence).join('<br>') || r.note || '';
    const notes = [...(r.requiresComponents?.length ? [`Needs: ${r.requiresComponents.join(', ')}`] : []), ...r.knownIssues, ...(r.restrictions || []).map((x) => x.text)].join('<br>');
    return `| ${r.version} | ${r.date} | ${r.channel} | ${fw} | ${cell(ev)} | ${cell(notes)} |`;
  });
  const features = d.features.map((f) => `| ${cell(f.label)} | ${f.since ?? `not documented (README for ${d.readmeDescribes})`} | ${[f.experimental ? 'experimental' : '', f.firmware ? `firmware ${f.firmware[0]}–${f.firmware[1]} only` : '', f.requires?.length ? `needs ${f.requires.join(', ')}` : '', f.note ?? ''].filter(Boolean).join('; ')} |`);
  return `## ${d.name} (${platform})

- **Last verified:** ${d.lastVerified}
- **Loading:** ${d.loading}
- **Firmware lists:** ${d.firmwareListNote}
- **Sources:** ${d.sources.map((s) => `[${s.label}](${s.url})`).join(' · ')}

### Releases and documented firmware

| Release | Date | Channel | Firmware stated by this release | Evidence | Requirements, known issues, restrictions |
|---|---|---|---|---|---|
${rows.join('\n')}

### Features

| Feature | First release that documents it | Notes |
|---|---|---|
${features.join('\n')}
`;
}

const goldhen = read('shared/compatibility/goldhen.json');
const etahen = read('shared/compatibility/etahen.json');
write('docs/compatibility.md', `# Firmware and environment compatibility

> Generated by \`node tools/build-docs.mjs\` from \`shared/compatibility/*.json\`. Edit the JSON, not this file.

These tables list what each GoldHEN and etaHEN release documents in its own release notes or files. Nothing is carried over from one release to the next, and nothing is guessed. The compatibility engine uses exactly this data.

## How the engine reads this data

| Situation | Status |
|---|---|
| Console not connected, or detection failed | **Not detected** |
| Not identified as a PS4 or PS5 | **Unknown** |
| Model, firmware or homebrew environment not reported, not verified, or not identified | **Unknown** |
| Homebrew environment version not in the researched data | **Unknown** |
| etaHEN: firmware mentioned by other releases but not by the installed one | **Unknown** (not assumed to carry over) |
| No release of the environment mentions the firmware | **Unsupported** |
| GoldHEN: the installed release's complete firmware list does not include the firmware | **Unsupported** |
| GoldHEN or etaHEN not running, or the other console's environment reported | **Unsupported** |
| The installed release documents the firmware only as limited or untested, or disables some features on it | **Partially compatible** |
| Model, firmware and environment identified and verified, and the installed release documents the firmware | **Compatible** |

The worst check decides the result, and every result lists a reason for each check. A final guard turns any "compatible" or "partially compatible" into "unknown" if a detail is not verified.

**Review decision (Stage 3, kept):** the strict etaHEN rule stays. If an etaHEN release does not itself establish a firmware, the result is Unknown, not Compatible — even for the latest release, and even when an earlier release documented that firmware. The engine is not loosened on assumptions. \`tests/compat.test.mjs\` checks this for every etaHEN release against every tested firmware.

${environmentDoc(goldhen, 'PS4')}
${environmentDoc(etahen, 'PS5')}
## Not verified

- GoldHEN betas 2.4b5–2.4b16.2 appear in the changelog but were not published as GitHub releases; they are not in the data.
- etaHEN releases with no firmware statement (2.5B, 2.2, 1.08b, 1.7b, 1.5b, 1.21b, 1.1b, 1.0b) are never rated compatible.
- Release dates come from the GitHub release pages and the repositories' tag dates; release asset file names were not inspected.
- PS4 and PS5 model groups are named from Sony's model numbering; no model-specific homebrew requirement was found in either project's documentation.
`);

const c = read('shared/customization.json');
const LEVEL_TITLE = { official: '1. Officially supported', homebrew: '2. Supported by documented homebrew', experimental: '3. Experimental or version-dependent', unsupported: '4. Unsupported (no documented method found)' };
const table = (items) => `| Area | What | Sources |\n|---|---|---|\n${items.map((x) => `| ${x.area} | ${cell(x.text)} | ${x.sources.map((s) => `[${c.sources[s].label}](${c.sources[s].url})`).join('<br>') || '—'} |`).join('\n')}`;
const platformDoc = (name, items) => `## ${name}\n\n${Object.keys(LEVEL_TITLE).map((l) => `### ${LEVEL_TITLE[l]}\n\n${table(items.filter((x) => x.level === l))}`).join('\n\n')}`;
write('docs/customization.md', `# What can be customised on PS4 and PS5

> Generated by \`node tools/build-docs.mjs\` from \`shared/customization.json\` (last verified ${c.lastVerified}). Edit the JSON, not this file.

## Theme, overlay, homebrew app, shell replacement

| Term | Meaning |
|---|---|
| Theme | ${c.terms.theme} |
| Overlay | ${c.terms.overlay} |
| Homebrew application | ${c.terms['homebrew-app']} |
| Home redirect | ${c.terms['home-redirect']} |
| System shell replacement | ${c.terms['shell-replacement']} |

**What this means for VantaFlow:** on a console, VantaFlow can realistically be a homebrew application (like Itemzflow), optionally opened through a home redirect that GoldHEN/Itemzflow or etaHEN already document. It does not and cannot claim to replace the PlayStation dashboard: no documented method exists for that.

Areas covered: backgrounds and themes, game artwork, game library presentation, home screen appearance, application presentation, interface overlays, custom menus and profile appearance.

${platformDoc('PS4', c.ps4)}

${platformDoc('PS5', c.ps5)}

## Source quality

PS4 official features come from PlayStation Blog posts. PS5 official features come from secondary sources (news sites) because no official PlayStation page was found in this research; check them on a console before relying on them. Homebrew features come from each project's own README and release notes.
`);
